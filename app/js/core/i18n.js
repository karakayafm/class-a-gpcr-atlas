let lang = "tr";
export function setLang(l) { lang = (l === "en" || l === "tr") ? l : "tr";
  try { localStorage.setItem("atlas.lang", lang); } catch (e) {}
  document.documentElement.setAttribute("lang", lang); }
export function getLang() { return lang; }
export function initLang() {
  let s = null; try { s = localStorage.getItem("atlas.lang"); } catch (e) {}
  setLang(s === "en" ? "en" : "tr"); }
export function t(key, vars) {
  let s = (DICT[lang] && DICT[lang][key]) || (DICT.en[key]) || key;
  if (vars) for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(String(vars[k]));
  return s; }
export function siteClassLabel(id) { return t("sc_" + id); }
export function stateLabel(id) { return t("st_" + id); }
export function warnLabel(id) { return t("w_" + id); }
